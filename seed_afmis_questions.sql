IF NOT EXISTS (SELECT 1 FROM [dbo].[tst_user_detail_q_values] WHERE [user_id] = '100')
BEGIN
    INSERT INTO [dbo].[tst_user_detail_q_values] ([user_id], [value_id], [new_value_id], [note], [rating], [score], [defect_category], [evidence], [eval_date])
    SELECT 
        '100' AS [user_id],
        [value_id],
        [value_id] AS [new_value_id],
        CASE 
            WHEN [defect_category] = N'إداري' THEN N'يتطلب تحديث لائحة الصلاحيات واعتماد التوقيع الرقمي بقرار وزاري'
            WHEN [defect_category] = N'فني' THEN N'تم فحص خادم SQL Server وتبين الحاجة لزيادة الذاكرة وتحسين سرعة خط الألياف'
            WHEN [defect_category] = N'برمجي' THEN N'الوظائف مكتملة مع وجود بطء بسيط عند استخراج ميزان المراجعة الموسع'
            ELSE N'تمت التوصية بدورة تنشيطية للمحاسبين على نماذج التسويات'
        END AS [note],
        CASE 
            WHEN [value_id] % 4 = 0 THEN 4
            WHEN [value_id] % 4 = 1 THEN 3
            WHEN [value_id] % 4 = 2 THEN 5
            ELSE 4
        END AS [rating],
        CASE 
            WHEN [value_id] % 4 = 0 THEN 4.0
            WHEN [value_id] % 4 = 1 THEN 3.0
            WHEN [value_id] % 4 = 2 THEN 5.0
            ELSE 4.0
        END AS [score],
        [defect_category],
        N'تقرير المعاينة الميدانية للوحدة التنفيذية - الدورة المالية 2026' AS [evidence],
        GETDATE() AS [eval_date]
    FROM [dbo].[tst_system_q_values]
    WHERE [survey_id] = 101;

    PRINT N'Sample consultant evaluations seeded successfully.';
END
